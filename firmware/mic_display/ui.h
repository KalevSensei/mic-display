// ---------------------------------------------------------------- canvas
const int W = 466, H = 466;
const float C = 233.0f;              // centre (pixel edges 0..466)
const float DEG = 0.0174532925f;
// The band being drawn: rows CLY0..CLY1-1 of the screen, W pixels each, RGB565. render() draws the whole
// screen into fb (the PC previews); the firmware calls renderBand() per band with its own buffers.
uint16_t *fb = nullptr;
int CLY0 = 0, CLY1 = H;
// Page offset while swiping: everything is drawn shifted right by OX and kept inside screen columns CX0..CX1-1.
int OX = 0, CX0 = 0, CX1 = W;

static inline int imin(int a, int b) { return a < b ? a : b; }
static inline int imax(int a, int b) { return a > b ? a : b; }
static inline float clampf(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
static inline float clamp01(float v) { return v < 0 ? 0 : (v > 1 ? 1 : v); }
static inline int xLo() { return CX0 - OX; }        // visible columns in drawing coordinates
static inline int xHi() { return CX1 - 1 - OX; }
constexpr uint16_t rgb(uint8_t r, uint8_t g, uint8_t b) { return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3); }
constexpr uint16_t rgbA(uint32_t hex, int pct) {   // a colour at pct % over black
  return rgb((uint8_t)(((hex >> 16) & 255) * pct / 100), (uint8_t)(((hex >> 8) & 255) * pct / 100), (uint8_t)((hex & 255) * pct / 100));
}

