// ---------------------------------------------------------------- PC -> board
static int split(char *p, char **f, int max) {   // comma-separated fields, in place
  int n = 0;
  f[n++] = p;
  while (*p && n < max) { if (*p == ',') { *p = 0; f[n++] = p + 1; } p++; }
  return n;
}
static bool dash(const char *s) { return !s[0] || (s[0] == '-' && s[1] == 0); }   // "-" = unknown / not available
static int field(const char *s) { return dash(s) ? -1 : atoi(s); }
static void parseSide(PcSide &s, char **f, int n, uint32_t now) {
  if (n < 4) return;
  int mute = field(f[0]), vol = field(f[1]), idx = field(f[2]), count = field(f[3]);
  if (now >= s.holdMute) s.mute = mute < 0 ? -1 : (mute ? 1 : 0);
  if (now >= s.holdVol) s.vol = vol < 0 ? -1 : (int8_t)(vol > 100 ? 100 : vol);
  s.count = count < 0 ? 0 : (uint8_t)imin(count, MAX_DEV);
  if (s.count > n - 4) s.count = n - 4;
  for (int i = 0; i < s.count; i++) { strncpy(s.names[i], f[4 + i], 31); s.names[i][31] = 0; }
  if (now >= s.holdIdx) s.idx = (idx < 0 || idx >= s.count) ? -1 : idx;
  s.at = now;
}
void onLine(char *ln, uint32_t now) {
  char *f[40];
  if (!ln[0] || ln[1] != ',') return;
  char type = ln[0];
  int n = split(ln + 2, f, 40);
  dirty = true;
  if (type == 'S' && n >= 6) {   // S,<level dB x10>,<peak dB x10>,<clip 0|1>,<reserved 0>,<sample rate Hz>,<device name>
    bool was = live(now);
    level = atoi(f[0]) / 10.0f;
    float pk = atoi(f[1]) / 10.0f;
    int hold = PEAK_S[set.peakIdx];
    if (hold == 0) heldPeak = pk;
    else if (pk >= heldPeak || now - heldAt > (uint32_t)hold * 1000) { heldPeak = pk; heldAt = now; }
    int c = atoi(f[2]);
    if (c && !clip) clipCount++;
    clip = c; rec = atoi(f[3]); rate = atol(f[4]);
    strncpy(name, f[5], sizeof name - 1); name[sizeof name - 1] = 0;
    lastFrame = now;
    if (level > SILENT_DB || !loudAt) loudAt = now;   // first frame starts the 3 s clock
    if (level > SILENT_DB) soundAt = now;
    if (!was) hello(now);   // the link just came up: tell the PC side who we are and what we show
  } else if (type == 'F' && n >= 1) {   // F,<n>,<b1>,...,<bn>, each 0..100
    int cnt = imin(imin(atoi(f[0]), 32), n - 1);
    for (int i = 0; i < cnt; i++) bands[i] = (uint8_t)imin(imax(atoi(f[1 + i]), 0), 100);
    nBands = cnt < 0 ? 0 : cnt; bandsAt = now;
  } else if (type == 'L' && n >= 4) {   // L,<short-term LUFS x10>,<session LUFS x10>,<talk s>,<session s>
    lufsS = dash(f[0]) ? NAN : atoi(f[0]) / 10.0f;
    lufsI = dash(f[1]) ? NAN : atoi(f[1]) / 10.0f;
    talkS = field(f[2]); sessionS = field(f[3]);
    loudnessAt = now;
  } else if (type == 'T' && n >= 2) {   // T,<unix seconds>,<UTC offset minutes>
    clockUnix = strtoll(f[0], nullptr, 10); clockOffMin = atol(f[1]); clockAt = now; clockValid = clockUnix > 0;
  } else if (type == 'H' && n >= 1) {   // H,<client name>,<protocol version>
    strncpy(client, f[0], sizeof client - 1); client[sizeof client - 1] = 0; clientAt = now;
  } else if (type == 'P') parseSide(pin, f, n, now);    // P,<mute>,<vol>,<index>,<count>,<name 1>,...
  else if (type == 'O') parseSide(pout, f, n, now);     // O,<mute>,<vol>,<index>,<count>,<name 1>,...
}

