bool avail(int it, uint32_t now) {
  switch (it) {
    case IT_MIC_MUTE: return sideLive(pin, now) && pin.mute >= 0;
    case IT_MIC_DEV: return sideLive(pin, now) && pin.idx >= 0 && pin.count > 0;
    case IT_MIC_VOL: return sideLive(pin, now) && pin.vol >= 0;
    case IT_OUT_DEV: return sideLive(pout, now) && pout.idx >= 0 && pout.count > 0;
    case IT_OUT_VOL: return sideLive(pout, now) && pout.vol >= 0;
    case IT_OUT_MUTE: return sideLive(pout, now) && pout.mute >= 0;
    default: return true;
  }
}

