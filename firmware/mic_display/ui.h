void fmtLufs(float v, char *t, int size) {   // "−18.4" with a true minus sign; "–∞" below −70 or unknown
  if (isnan(v) || v < -70) { snprintf(t, size, "\xE2\x80\x93\xE2\x88\x9E"); return; }
  int d = (int)lroundf(v * 10);
  if (d < 0) snprintf(t, size, "\xE2\x88\x92%d.%d", -d / 10, -d % 10);
  else snprintf(t, size, "%d.%d", d / 10, d % 10);
}
