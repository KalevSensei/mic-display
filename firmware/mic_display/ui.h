// Civil date from days since 1970-01-01 (Howard Hinnant's algorithm).
void civil(long long z, int &y, int &m, int &d) {
  z += 719468;
  long long era = (z >= 0 ? z : z - 146096) / 146097;
  unsigned doe = (unsigned)(z - era * 146097);
  unsigned yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  unsigned doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  unsigned mp = (5 * doy + 2) / 153;
  d = doy - (153 * mp + 2) / 5 + 1;
  m = mp < 10 ? mp + 3 : mp - 9;
  y = (int)(yoe + era * 400) + (m <= 2);
}
// Clock: time from the PC (T line), kept by the board between updates; 60 minute ticks, the seconds sweep lit.
void faceClock(uint32_t now) {
  if (clip && live(now)) ring(106.5f * K, 109 * K, 0, 360, RED);
  int sec = -1;
  char t[16] = "--:--", d[40] = "";
  if (clockValid) {
    long long u = clockUnix + (long long)((now - clockAt) / 1000) + clockOffMin * 60;
    long long days = u >= 0 ? u / 86400 : (u - 86399) / 86400;
    long s = (long)(u - days * 86400);
    sec = s % 60;
    snprintf(t, sizeof t, "%02ld:%02ld", s / 3600, s / 60 % 60);
    int y, m, dd;
    civil(days, y, m, dd);
    static const char *const WD[7] = {"Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"};
    static const char *const MO[12] = {"Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"};
    snprintf(d, sizeof d, "%s %d %s", WD[(int)(((days % 7) + 11) % 7)], dd, MO[m - 1]);
  }
  for (int i = 0; i < 60; i++) {
    float a = (-90 + i * 6) * DEG, ca = cosf(a), sa = sinf(a);
    bool five = i % 5 == 0;
    uint16_t col = sec < 0 ? (five ? FAINT : LINE) : i == sec ? TEXT : i < sec ? DIM : (five ? FAINT : LINE);
    line(C + ca * (five ? 94 : 98) * K, C + sa * (five ? 94 : 98) * K, C + ca * 104 * K, C + sa * 104 * K, (five ? 0.9f : 0.55f) * K, false, col);
  }
  centered(F_HUGE, t, C, C + 14 * K, clockValid ? TEXT : DIM);
  centered(F_MSG, clockValid ? d : "time comes from the PC", C, C + 42 * K, DIM);
}

// Page dots along the bottom arc: n dots, the active one larger and white.
