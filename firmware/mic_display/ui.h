// 5 · Bars: 32 frequency bands as round-capped spokes from bass (lower left) over the top to treble (lower right).
void faceBars(uint32_t now) {
  if (!facePrelude(now)) return;
  int n = nBands > 0 ? nBands : 32;
  float slot = (ARC_TO - ARC_FROM) / n, r0 = 124, len = 76;
  for (int i = 0; i < n; i++) {
    float a = ARC_FROM + (i + 0.5f) * slot, v = clamp01(bandS[i] / 100.0f);
    radial(r0, r0 + len, a, 3.5f, true, FILL_D);
    radial(r0, r0 + len * v, a, 3.5f, true, v > 0.88f ? RED : v > 0.70f ? YELLOW : GREEN);
  }
  levelNumber(F_NUM, C + 27, now);
}

// 6 · Loudness: short-term LUFS big, the session's integrated loudness as a line and a white dot on the arc.
void faceLoud(uint32_t now) {
  if (!facePrelude(now)) return;
  bool fresh = loudnessAt && now - loudnessAt < 2000;
  float s = fresh ? lufsS : NAN, in = fresh ? lufsI : NAN;
  scaleArc(isnan(s) ? 0 : (s + 50) / 50, GREEN_T, GREEN);
  if (!isnan(in) && in >= -50) {
    float a = ARC_FROM + (clampf(in, -50, 0) + 50) / 50 * (ARC_TO - ARC_FROM);
    disc(px(200, a), py(200, a), 9, BG);
    disc(px(200, a), py(200, a), 6.5f, WHITE);
  }
  char t[16], v[16];
  fmtLufs(s, t, sizeof t);
  centered(F_HUGE, t, C, C + 36, WHITE);
  centered(F_CAP, "LUFS", C, C + 72, SECOND);
  fmtLufs(in, v, sizeof v);
  const char *lab = "Session ";
  float w = textWidth(F_BODY, lab) + textWidth(F_BODY, v);
  float x = textAt(F_BODY, lab, C - w / 2, (int)lroundf(C + 122), SECOND);
  textAt(F_BODY, v, x, (int)lroundf(C + 122), WHITE);
}

// 7 · Talk time: how long the voice was above the silence floor this session; the arc = share of the session.
void faceTalk(uint32_t now) {
  if (!facePrelude(now)) return;
  bool fresh = loudnessAt && now - loudnessAt < 2000;
  long tk = fresh ? talkS : -1, se = fresh ? sessionS : -1;
  scaleArc(tk >= 0 && se > 0 ? (float)tk / se : 0, CYAN_T, CYAN);
  char t[20], s[20], l[32];
  fmtDuration(tk, t, sizeof t);
  centered(tk >= 3600 ? F_NUM : F_HUGE, t, C, C + 36, WHITE);
  fmtDuration(se, s, sizeof s);
  snprintf(l, sizeof l, "of %s", s);
  centered(F_BODY, l, C, C + 80, SECOND);
  bool talking = !silent(now) && level > SILENT_DB;
  const char *w = talking ? "Talking" : "Quiet";
  float tw = textWidth(F_CAP, w), x = C - (tw + 16) / 2;
  disc(x + 5, C + 121, 5, talking ? GREEN : TERT);
  textAt(F_CAP, w, x + 16, (int)lroundf(C + 128), talking ? GREEN : SECOND);
}

// 8 · Clock: time from the PC (T line), kept by the board between updates; 60 ticks, the second in orange.
void faceClock(uint32_t now) {
  clipRing(now);
  char hm[8], date[24];
  int sec = -1;
  bool tv = clockNow(now, hm, sizeof hm, date, sizeof date, sec);
  for (int i = 0; i < 60; i++) {
    float a = -90 + i * 6;
    bool five = i % 5 == 0;
    if (tv && i == sec) continue;
    uint16_t col = five ? (tv && i < sec ? WHITE : SECOND) : (tv && i < sec ? SECOND : TERT);
    radial(five ? 186 : 194, 205, a, five ? 1.5f : 0.8f, false, col);
  }
  if (tv) radial(180, 205, -90 + sec * 6, 2, true, ORANGE);
  centered(F_BODY, tv ? date : "Time comes from the PC", C, C - 74, tv ? ORANGE : SECOND);
  centered(F_HUGE, tv ? hm : "\xE2\x80\x93\xE2\x80\x93:\xE2\x80\x93\xE2\x80\x93", C, C + 38, tv ? WHITE : TERT);
  if (live(now)) levelBar(C - 64, C + 64, C + 96, 4);
}

