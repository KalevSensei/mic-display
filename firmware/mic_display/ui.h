// ---------------------------------------------------------------- anti-aliased drawing into fb
static inline void blend(int x, int y, uint16_t c, uint32_t a /* 0..256 */) {
  if (a == 0 || (unsigned)x >= (unsigned)W || (unsigned)y >= (unsigned)H) return;
  uint16_t *p = fb + y * W + x;
  if (a >= 256) { *p = c; return; }
  uint32_t d = *p;
  int r = (d >> 11) + ((((int)(c >> 11) - (int)(d >> 11)) * (int)a) >> 8);
  int g = ((d >> 5) & 63) + ((((int)((c >> 5) & 63) - (int)((d >> 5) & 63)) * (int)a) >> 8);
  int b = (d & 31) + ((((int)(c & 31) - (int)(d & 31)) * (int)a) >> 8);
  *p = (r << 11) | (g << 5) | b;
}
static inline void cover(int x, int y, uint16_t c, float cov) { blend(x, y, c, (uint32_t)(cov * 256.0f + 0.5f)); }

// Ring segment around (cx, cy) between radii ri..ro from angle a0 to a1 (degrees, clockwise from 3 o'clock,
// like the page's canvas). Sweeps over 180 degrees are split; the split seams are hard so they leave no line.
void arc(float cx, float cy, float ri, float ro, float a0, float a1, uint16_t col, bool aa0 = true, bool aa1 = true) {
  if (a1 <= a0) return;
  bool full = a1 - a0 >= 360;
  if (!full && a1 - a0 > 180) { float m = (a0 + a1) / 2; arc(cx, cy, ri, ro, a0, m, col, aa0, false); arc(cx, cy, ri, ro, m, a1, col, false, aa1); return; }
  float sx = cosf(a0 * DEG), sy = sinf(a0 * DEG), ex = cosf(a1 * DEG), ey = sinf(a1 * DEG);
  float bx0 = cx + ro, by0 = cy + ro, bx1 = cx - ro, by1 = cy - ro;
  auto grow = [&](float x, float y) { bx0 = fminf(bx0, x); bx1 = fmaxf(bx1, x); by0 = fminf(by0, y); by1 = fmaxf(by1, y); };
  if (full) { grow(cx - ro, cy - ro); grow(cx + ro, cy + ro); }
  else {
    for (float r : {ri, ro}) { grow(cx + sx * r, cy + sy * r); grow(cx + ex * r, cy + ey * r); }
    for (int q = -720; q <= 720; q += 90) if (q > a0 && q < a1) grow(cx + cosf(q * DEG) * ro, cy + sinf(q * DEG) * ro);
  }
  int y0 = imax(0, (int)floorf(by0 - 1)), y1 = imin(H - 1, (int)ceilf(by1 + 1));
  int x0 = imax(0, (int)floorf(bx0 - 1)), x1 = imin(W - 1, (int)ceilf(bx1 + 1));
  float ri2 = (ri - 0.5f) * (ri - 0.5f), ro2 = (ro + 0.5f) * (ro + 0.5f);
  float in2 = (ri + 0.5f) * (ri + 0.5f), out2 = (ro - 0.5f) * (ro - 0.5f);
  if (ri < 0.5f) ri2 = -1;
  for (int y = y0; y <= y1; y++) {
    float py = y + 0.5f - cy, py2 = py * py;
    if (py2 > ro2) continue;
    // visit only the ring: the outer circle's chord minus the inner circle's chord
    float ho = sqrtf(ro2 - py2), hi = py2 < ri2 ? sqrtf(ri2 - py2) : 0;
    int xa = imax(x0, (int)floorf(cx - ho)), xb = imin(x1, (int)ceilf(cx + ho));
    int ia = (int)ceilf(cx - hi) + 1, ib = (int)floorf(cx + hi) - 2;   // fully inside the hole
    for (int x = xa; x <= xb; x++) {
      if (x >= ia && x <= ib) { x = ib; continue; }
      float px = x + 0.5f - cx, d2 = px * px + py2;
      if (d2 < ri2 || d2 > ro2) continue;
      float cov = 1;
      if (d2 < in2 || d2 > out2) { float d = sqrtf(d2); cov = clamp01(d - ri + 0.5f) * clamp01(ro - d + 0.5f); }
      if (!full) {
        float cs = sx * py - sy * px, ce = px * ey - py * ex;   // distance past the start ray / before the end ray
        if (cs < -0.5f || ce < -0.5f) continue;
        if (aa0) cov *= clamp01(cs + 0.5f); else if (cs < 0) continue;
        if (aa1) cov *= clamp01(ce + 0.5f); else if (ce < 0) continue;
      }
      cover(x, y, col, cov);
    }
  }
}
void ring(float ri, float ro, float a0, float a1, uint16_t col, bool aa0 = true, bool aa1 = true) { arc(C, C, ri, ro, a0, a1, col, aa0, aa1); }
void disc(float cx, float cy, float r, uint16_t col) {
  for (int y = imax(0, (int)floorf(cy - r - 1)); y <= imin(H - 1, (int)ceilf(cy + r + 1)); y++)
    for (int x = imax(0, (int)floorf(cx - r - 1)); x <= imin(W - 1, (int)ceilf(cx + r + 1)); x++) {
      float dx = x + 0.5f - cx, dy = y + 0.5f - cy;
      cover(x, y, col, clamp01(r + 0.5f - sqrtf(dx * dx + dy * dy)));
    }
}
// Line of half-width hw from (ax,ay) to (bx,by); round or butt ends, like the page's lineCap.
void line(float ax, float ay, float bx, float by, float hw, bool round, uint16_t col) {
  float dx = bx - ax, dy = by - ay, len = sqrtf(dx * dx + dy * dy);
  if (len < 0.01f) { if (round) disc(ax, ay, hw, col); return; }
  dx /= len; dy /= len;
  float m = hw + 1;
  int y0 = imax(0, (int)floorf(fminf(ay, by) - m)), y1 = imin(H - 1, (int)ceilf(fmaxf(ay, by) + m));
  int x0 = imax(0, (int)floorf(fminf(ax, bx) - m)), x1 = imin(W - 1, (int)ceilf(fmaxf(ax, bx) + m));
  for (int y = y0; y <= y1; y++)
    for (int x = x0; x <= x1; x++) {
      float px = x + 0.5f - ax, py = y + 0.5f - ay;
      float s = fabsf(px * dy - py * dx);
      if (s > m) continue;
      float t = px * dx + py * dy, cov;
      if (round) {
        float d = t < 0 ? sqrtf(px * px + py * py) : t > len ? sqrtf((t - len) * (t - len) + s * s) : s;
        cov = clamp01(hw + 0.5f - d);
      } else cov = clamp01(hw + 0.5f - s) * clamp01(t + 0.5f) * clamp01(len - t + 0.5f);
      cover(x, y, col, cov);
    }
}
// Filled convex polygon, n points as x,y pairs, anti-aliased edges.
void poly(const float *p, int n, uint16_t col) {
  float area = 0, bx0 = 1e9f, by0 = 1e9f, bx1 = -1e9f, by1 = -1e9f;
  for (int i = 0; i < n; i++) {
    int j = (i + 1) % n;
    area += p[2 * i] * p[2 * j + 1] - p[2 * j] * p[2 * i + 1];
    bx0 = fminf(bx0, p[2 * i]); bx1 = fmaxf(bx1, p[2 * i]); by0 = fminf(by0, p[2 * i + 1]); by1 = fmaxf(by1, p[2 * i + 1]);
  }
  float sg = area > 0 ? 1.0f : -1.0f;
  for (int y = imax(0, (int)floorf(by0 - 1)); y <= imin(H - 1, (int)ceilf(by1 + 1)); y++)
    for (int x = imax(0, (int)floorf(bx0 - 1)); x <= imin(W - 1, (int)ceilf(bx1 + 1)); x++) {
      float px = x + 0.5f, py = y + 0.5f, d = 1e9f;
      for (int i = 0; i < n; i++) {
        int j = (i + 1) % n;
        float ex = p[2 * j] - p[2 * i], ey = p[2 * j + 1] - p[2 * i + 1], len = sqrtf(ex * ex + ey * ey);
        if (len < 1e-4f) continue;
        d = fminf(d, sg * (ex * (py - p[2 * i + 1]) - ey * (px - p[2 * i])) / len);
      }
      cover(x, y, col, clamp01(d + 0.5f));
    }
}

// ---------------------------------------------------------------- text: UTF-8, y = baseline
uint32_t nextCp(const char *&s) {
  uint8_t c = *s++;
  if (c < 0x80) return c;
  int n = c >= 0xF0 ? 3 : c >= 0xE0 ? 2 : c >= 0xC0 ? 1 : -1;
  if (n < 0) return '?';
  uint32_t cp = c & (0x3F >> n);
  while (n--) { if ((*s & 0xC0) != 0x80) return '?'; cp = (cp << 6) | (*s++ & 0x3F); }
  return cp;
}
const MDGlyph *glyph(const MDFont &f, uint32_t cp) {
  int lo = 0, hi = f.count - 1;
  while (lo <= hi) { int m = (lo + hi) / 2; if (f.glyphs[m].code == cp) return &f.glyphs[m]; if (f.glyphs[m].code < cp) lo = m + 1; else hi = m - 1; }
  return cp == '?' ? nullptr : glyph(f, '?');
}
// track = extra space between letters in px (tracked capitals)
float textWidth(const MDFont &f, const char *s, float track = 0) {
  float w = 0; int n = 0;
  while (*s) { const MDGlyph *g = glyph(f, nextCp(s)); if (g) { w += g->adv4 / 4.0f; n++; } }
  return w + (n > 1 ? track * (n - 1) : 0);
}
float textAt(const MDFont &f, const char *s, float x, int baseline, uint16_t col, float track = 0) {
  float pen = x;
  while (*s) {
    const MDGlyph *g = glyph(f, nextCp(s));
    if (!g) continue;
    const uint8_t *bits = f.bits + g->offset;
    int gx = (int)lroundf(pen) + g->x, gy = baseline + g->y;
    for (int i = 0, n = g->w * g->h; i < n; i++) {
      uint8_t a = (bits[i >> 1] >> ((i & 1) ? 0 : 4)) & 15;
      if (a) blend(gx + i % g->w, gy + i / g->w, col, a * 17 + (a * 17 >> 7));   // 15 -> 256
    }
    pen += g->adv4 / 4.0f + track;
  }
  return pen - track;
}
void centered(const MDFont &f, const char *s, float x, float baseline, uint16_t col, float track = 0) {
  textAt(f, s, x - textWidth(f, s, track) / 2, (int)lroundf(baseline), col, track);
}
// Copy s into out, cut to maxW px with "..." when it does not fit.
void fitText(const MDFont &f, const char *s, float maxW, char *out, int size) {
  strncpy(out, s, size - 1); out[size - 1] = 0;
  if (textWidth(f, out) <= maxW) return;
  int n = strlen(out);
  while (n > 0) {
    do n--; while (n > 0 && (out[n] & 0xC0) == 0x80);   // step back one whole UTF-8 character
    while (n > 0 && out[n - 1] == ' ') n--;
    if (n + 4 > size) continue;
    strcpy(out + n, "...");
    if (textWidth(f, out) <= maxW) return;
  }
}
// Split s into at most two lines at a space, each within its width; the second is cut with "..." if needed.
int wrap2(const MDFont &f, const char *s, float w1, float w2, char *l1, char *l2, int size) {
  l2[0] = 0;
  if (textWidth(f, s) <= w1) { fitText(f, s, w1, l1, size); return 1; }
  int best = -1, n = strlen(s);
  char tmp[96];
  for (int i = 1; i < n && i < (int)sizeof tmp - 1; i++)
    if (s[i] == ' ') { memcpy(tmp, s, i); tmp[i] = 0; if (textWidth(f, tmp) <= w1) best = i; }
  if (best < 0) { fitText(f, s, w1, l1, size); return 1; }
  memcpy(l1, s, imin(best, size - 1)); l1[imin(best, size - 1)] = 0;
  fitText(f, s + best + 1, w2, l2, size);
  return 2;
}

