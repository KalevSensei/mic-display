// ---------------------------------------------------------------- one frame
int pagerCount() { return inSettings ? IT_COUNT : FACE_COUNT; }
int pagerPos() { return inSettings ? item : facePos(set.face); }
void drawPageAt(int pos, int off, uint32_t now) {
  OX = off; CX0 = imax(0, off); CX1 = imin(W, W + off);
  if (CX0 < CX1) { if (inSettings) drawItem(pos, now); else drawFace(FACE_ORDER[pos], now); }
  OX = 0; CX0 = 0; CX1 = W;
}
// Draw screen rows y0..y1-1 into buf (W pixels per row). The firmware calls it band by band each frame,
// after animate(); everything outside the band is skipped cheaply.
void renderBand(uint32_t now, int y0, int y1, uint16_t *buf) {
  fb = buf; CLY0 = y0; CLY1 = y1;
  memset(buf, 0, (size_t)(y1 - y0) * W * 2);
  int pos = pagerPos(), n = pagerCount(), off = (int)lroundf(pageOff);
  drawPageAt(pos, off, now);
  if (off > 0 && pos > 0) drawPageAt(pos - 1, off - W, now);
  if (off < 0 && pos < n - 1) drawPageAt(pos + 1, off + W, now);
  if (inSettings) {
    line(C - 44, DONE_Y, C + 44, DONE_Y, 28, true, pressed == Z_DONE ? FILL_P : FILL);   // Done pill, 144 x 56
    centered(F_TITLE, "Done", C, DONE_Y + 12, WHITE);
    dots(IT_COUNT, item, 202, 4.4f);
  } else if (paging || off != 0 || now - faceShownAt < FACE_DOTS_MS) dots(FACE_COUNT, pos, 201, 5.4f);
}
void render(uint32_t now) { renderBand(now, 0, H, fb); }   // the whole screen into fb (PC previews)

// ---------------------------------------------------------------- changing settings
void save() { if (settingsDirty && onSave) onSave(); settingsDirty = false; }
void setVol(int it, int v, uint32_t now, bool sendIt) {
  v = imax(ringMin(it), imin(100, v));
  if (it == IT_BRIGHT) {
    if (v == set.brightness) return;
    set.brightness = v; settingsDirty = true;
    if (onBrightness) onBrightness(v);
    return;
  }
  PcSide &s = it == IT_MIC_VOL ? pin : pout;
  s.vol = v; s.holdVol = now + 1500;
  if (sendIt) cmd(it == IT_MIC_VOL ? "vol" : "outvol", v);
}
void step(int d, uint32_t now) {
  switch (item) {
    case IT_MIC_DEV: case IT_OUT_DEV: {
      PcSide &s = item == IT_MIC_DEV ? pin : pout;
      if (s.count < 2) return;
      s.idx = (s.idx + d + s.count) % s.count; s.holdIdx = now + 3000;
      cmd(item == IT_MIC_DEV ? "mic" : "out", s.idx);
      break;
    }
    case IT_MIC_VOL: case IT_OUT_VOL: setVol(item, ringValue(item) + d * 5, now, true); break;
    case IT_BRIGHT: setVol(item, (set.brightness + 5) / 10 * 10 + d * 10, now, false); break;
    case IT_SLEEP: set.sleepIdx = imax(0, imin(3, set.sleepIdx + d)); settingsDirty = true; break;
    case IT_PEAK: set.peakIdx = imax(0, imin(2, set.peakIdx + d)); settingsDirty = true; cmd("peakhold", PEAK_S[set.peakIdx]); break;
  }
}
void bigTap(uint32_t now) {
  if (item == IT_MIC_MUTE || item == IT_OUT_MUTE) {
    PcSide &s = item == IT_MIC_MUTE ? pin : pout;
    s.mute = s.mute == 1 ? 0 : 1; s.holdMute = now + 1500;
    cmd(item == IT_MIC_MUTE ? "mute" : "outmute", s.mute);
  } else if (item == IT_RESET) {
    heldPeak = MIN_DB; pkS = MIN_DB; heldAt = now; clipCount = 0; resetDoneAt = now;
    send("C,reset");
  }
}
void openSettings(uint32_t now) { inSettings = true; item = IT_MIC_MUTE; lastTouch = now; pageOff = 0; }
void closeSettings(uint32_t now) { inSettings = false; pressed = Z_NONE; faceShownAt = now; pageOff = 0; paging = false; save(); }
void showFace(int f, uint32_t now) {
  if (f < 0 || f >= FACE_COUNT || f == set.face) return;
  set.face = f; faceShownAt = now; settingsDirty = true; save();
  char t[32]; snprintf(t, sizeof t, "C,face,%s", FACE_ID[f]); send(t);
}
void goPage(int pos, uint32_t now) {
  if (inSettings) item = imax(0, imin(IT_COUNT - 1, pos));
  else showFace(FACE_ORDER[imax(0, imin(FACE_COUNT - 1, pos))], now);
}

// ---------------------------------------------------------------- touch
// Gestures: tap (moves < 30 px, shorter than 0.8 s); sideways drag = the page follows the finger, and on
// release it moves on when dragged past a fifth of the screen or flicked (over 0.35 px/ms), else springs back;
// at the first and last page it gives with resistance. Swipe down (90 px or more, mostly down) closes the
// settings. A drag that starts on a settings ring sets the value instead.
int downX, downY, curX, curY;
uint32_t downAt = 0, lastDragSend = 0;
bool swallow = false, dragging = false;

float angleAt(int x, int y) {   // 0..360 clockwise from 3 o'clock, folded onto the dial's 150..390 arc
  float a = atan2f(y + 0.5f - C, x + 0.5f - C) / DEG;
  if (a < 0) a += 360;
  if (a < 90) a += 360;
  return a;
}
int zoneAt(int x, int y) {
  if (!inSettings) return Z_NONE;
  if (x >= C - 72 && x <= C + 72 && y >= 352) return Z_DONE;
  Kind k = KIND[item];
  auto near = [&](float cx, float cy, float r) { float dx = x - cx, dy = y - cy; return dx * dx + dy * dy < r * r; };
  if (k == K_RING || k == K_DEVICE || k == K_CHOICE) {
    if (near(C - BTN_DX, BTN_Y, BTN_HIT)) return Z_MINUS;
    if (near(C + BTN_DX, BTN_Y, BTN_HIT)) return Z_PLUS;
  }
  if ((k == K_TOGGLE || k == K_ACTION) && near(C, BIG_Y, BIG_HIT)) return Z_BIG;
  if (k == K_RING) {
    float dx = x - C, dy = y - C, r = sqrtf(dx * dx + dy * dy), a = angleAt(x, y);
    if (r > 165 && r < 240 && a > 140 && a < 400) return Z_RING;
  }
  return Z_NONE;
}
void dragTo(int x, int y, uint32_t now, bool final) {
  float a = clampf(angleAt(x, y), ARC_FROM, ARC_TO), lo = ringMin(item);
  float v = lo + (a - ARC_FROM) / (ARC_TO - ARC_FROM) * (100 - lo);
  int iv = item == IT_BRIGHT ? (int)lroundf(v / 5) * 5 : (int)lroundf(v);
  bool sendIt = final || now - lastDragSend >= 100;
  if (sendIt && item != IT_BRIGHT) lastDragSend = now;
  setVol(item, iv, now, sendIt);
}
void wake(uint32_t now) {
  if (!asleep) return;
  asleep = false; dirty = true;
  if (onBrightness) onBrightness(set.brightness);
}
void touchDown(int x, int y, uint32_t now) {
  dirty = true;
  swallow = asleep;     // a touch on a dark screen only wakes it
  lastTouch = now;
  wake(now);
  downX = curX = lastMoveX = x; downY = curY = y; downAt = lastMoveAt = now; vel = 0;
  if (swallow) return;
  if (fabsf(pageOff) > 0.5f) { paging = true; pageBase = pageOff; pressed = Z_NONE; return; }   // catch a settling page
  paging = false;
  pressed = zoneAt(x, y);
  if (pressed == Z_RING && avail(item, now)) { dragging = true; dragTo(x, y, now, false); }
  if (!inSettings) faceShownAt = now;
}
void touchMove(int x, int y, uint32_t now) {
  curX = x; curY = y; lastTouch = now; dirty = true;
  if (swallow) return;
  if (dragging) { dragTo(x, y, now, false); return; }
  int dx = x - downX, dy = y - downY;
  if (!paging && abs(dx) > 14 && abs(dx) > abs(dy)) { paging = true; pageBase = 0; pressed = Z_NONE; }
  if (abs(dx) > 30 || abs(dy) > 30) pressed = Z_NONE;   // not a tap any more
  if (now > lastMoveAt) { float inst = (float)(x - lastMoveX) / (now - lastMoveAt); vel = 0.6f * inst + 0.4f * vel; }
  lastMoveX = x; lastMoveAt = now;
  if (paging) {
    float raw = pageBase + dx;
    int pos = pagerPos(), n = pagerCount();
    if ((raw > 0 && pos == 0) || (raw < 0 && pos == n - 1)) raw *= 0.3f;   // rubber band at the ends
    pageOff = clampf(raw, -W, W);
  }
}
void touchUp(uint32_t now) {
  lastTouch = now; dirty = true;
  int z = pressed;
  pressed = Z_NONE;
  if (swallow) { swallow = false; return; }
  if (dragging) { dragging = false; dragTo(curX, curY, now, true); return; }
  if (now - lastMoveAt > 80) vel = 0;   // the finger rested before lifting: no flick
  if (paging) {
    paging = false;
    int pos = pagerPos(), n = pagerCount();
    bool next = pageOff < 0 && pos < n - 1 && (pageOff < -W * 0.2f || vel < -0.35f);
    bool prev = pageOff > 0 && pos > 0 && (pageOff > W * 0.2f || vel > 0.35f);
    if (next) { pageOff += W; goPage(pos + 1, now); }
    else if (prev) { pageOff -= W; goPage(pos - 1, now); }
    if (!inSettings) faceShownAt = now;
    return;
  }
  int dx = curX - downX, dy = curY - downY;
  bool tap = abs(dx) < 30 && abs(dy) < 30 && now - downAt < 800;
  bool down = dy >= 90 && dy > 1.3f * abs(dx);
  if (!inSettings) { if (tap) openSettings(now); return; }
  if (down) { closeSettings(now); return; }
  if (!tap) return;
  bool ok = avail(item, now);
  if (z == Z_DONE) closeSettings(now);
  else if (!ok) return;   // greyed: nothing to change until the PC app answers
  else if (z == Z_MINUS) step(-1, now);
  else if (z == Z_PLUS) step(1, now);
  else if (z == Z_BIG) bigTap(now);
}

// ---------------------------------------------------------------- timers
void begin(uint32_t now) { bootAt = now; soundAt = now; faceShownAt = now; for (int i = 0; i < 32; i++) bandS[i] = 0; hello(now); }
void tick(uint32_t now) {
  if (inSettings && !paging && now - lastTouch > SETTINGS_IDLE_MS) { closeSettings(now); dirty = true; }
  if (now - lastHello >= HELLO_MS) hello(now);
  if (asleep && now - soundAt < 1000) wake(now);   // sound wakes it
  uint32_t idleMs = (uint32_t)SLEEP_MIN[set.sleepIdx] * 60000UL;
  uint32_t act = lastTouch > soundAt ? lastTouch : soundAt;
  if (!asleep && !inSettings && idleMs && now - act > idleMs) {
    asleep = true;
    if (onBrightness) onBrightness(0);
  }
}

