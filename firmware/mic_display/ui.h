// 1 · Dial: the level on a 240 degree gauge, an orange needle, the number below the hub.
void faceDial(uint32_t now) {
  if (!facePrelude(now)) return;
  // band r 192..204: dim zones, lit to the level, round ends
  const float r0 = 192, r1 = 204, rm = 198;
  ring(r0, r1, dbToDeg(MIN_DB), dbToDeg(Z_YELLOW), GREEN_T, false, false);
  ring(r0, r1, dbToDeg(Z_YELLOW), dbToDeg(Z_RED), YELLOW_T, false, false);
  ring(r0, r1, dbToDeg(Z_RED), dbToDeg(MAX_DB), RED_T, false, false);
  disc(px(rm, ARC_FROM), py(rm, ARC_FROM), 6, lvl > MIN_DB + 0.2f ? GREEN : GREEN_T);
  disc(px(rm, ARC_TO), py(rm, ARC_TO), 6, RED_T);
  if (lvl > MIN_DB + 0.2f) {
    ring(r0, r1, ARC_FROM, dbToDeg(fminf(lvl, Z_YELLOW)), GREEN, false, false);
    if (lvl > Z_YELLOW) ring(r0, r1, dbToDeg(Z_YELLOW), dbToDeg(fminf(lvl, Z_RED)), YELLOW, false, false);
    if (lvl > Z_RED) ring(r0, r1, dbToDeg(Z_RED), dbToDeg(lvl), RED, false, false);
    disc(px(rm, dbToDeg(lvl)), py(rm, dbToDeg(lvl)), 6, zoneCol(lvl));
  }
  // ticks: every 2 dB thin, every 10 dB longer; numbers only at -40, -20, 0
  for (int db = -60; db <= 0; db += 2) {
    bool major = db % 10 == 0;
    radial(major ? 164 : 172, 184, dbToDeg(db), major ? 1.4f : 0.8f, false, major ? SECOND : TERT);
  }
  static const char *const LAB[3] = {"\xE2\x88\x92" "40", "\xE2\x88\x92" "20", "0"};   // no "-60": the needle rests there in silence
  for (int i = 0; i < 3; i++) { float a = dbToDeg(-40 + i * 20); centered(F_CAP, LAB[i], px(140, a), py(140, a) + 8, SECOND); }
  if (pkS > MIN_DB) radial(186, 209, dbToDeg(pkS), 1.6f, true, pkS > Z_RED ? RED : WHITE);
  // needle: orange, 18 px behind the hub to 178 px out; hub ring
  float a = dbToDeg(lvl);
  line(px(-18, a), py(-18, a), px(178, a), py(178, a), 2.2f, true, ORANGE);
  disc(C, C, 10, ORANGE);
  disc(C, C, 4, BG);
  levelNumber(F_NUM, C + 112, now);
  if (!silent(now)) centered(F_CAP, "dB", C, C + 146, SECOND);
  if (clipCount) { char t[16]; snprintf(t, sizeof t, clipCount == 1 ? "%d clip" : "%d clips", clipCount); centered(F_CAP, t, C, C + 176, RED); }
}

// 2 · Rings (Activity style): outer = level, middle = held peak, inner = talk time's share of the session.
void faceRings(uint32_t now) {
  if (!facePrelude(now)) return;
  struct R { float ri, ro, t; uint16_t col, track; };
  bool fresh = loudnessAt && now - loudnessAt < 2000;
  float talk = fresh && talkS >= 0 && sessionS > 0 ? (float)talkS / sessionS : 0;
  const R rs[3] = {{170, 204, dbT(lvl), GREEN, GREEN_T}, {130, 164, dbT(pkS), ORANGE, ORANGE_T}, {90, 124, talk, CYAN, CYAN_T}};
  for (const R &r : rs) {
    ring(r.ri, r.ro, 0, 360, r.track);
    float t = clamp01(r.t) * 0.999f;
    roundArc(r.ri, r.ro, -90, -90 + 360 * t, r.col);
  }
  levelNumber(F_NUM, C + 27, now);
}

