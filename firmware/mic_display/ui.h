// Mic-stand audio display: everything the screen shows and every touch it understands.
// Plain C++ with no Arduino or hardware calls, so the same file is compiled twice:
//   - into the firmware (mic_display.ino feeds it serial lines, touch points and the clock, and pushes the
//     pixels), and
//   - on the PC by firmware/tools/previews.py, which renders docs/previews/settings/*.png from this exact code.
// Screen: 466 x 466 round AMOLED. The printed shell covers the glass outside a 424 px circle, so every
// element stays inside radius 212 around the centre.
// Look (owner, 2026-11-19: "make the ui cleaner call it apple style"): watchOS-like. Pure black, Apple's
// dark-mode system colours, Inter (a free look-alike of SF Pro) with tabular figures, few labels, thin ticks,
// round caps. Pages (faces, settings) follow the finger and settle with easing.
// Drawing works on a band of rows at a time (renderBand), so the firmware can draw into small buffers in fast
// internal RAM and push only the rows that changed while the next band is drawn.
// Protocol (both directions): docs/PROTOCOL.md.
