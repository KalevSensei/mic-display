// A horizontal level meter: grey track, lit green / yellow / red up to the level, a white peak tick.
void levelBar(float x0, float x1, float y, float hw) {
  line(x0, y, x1, y, hw, true, FILL);
  float t = dbT(lvl), xa = x0, span = x1 - x0;
  if (lvl > MIN_DB + 0.2f) {
    float xy = x0 + span * dbT(Z_YELLOW), xr = x0 + span * dbT(Z_RED), xe = x0 + span * t;
    line(xa, y, fminf(xe, xy), y, hw, true, GREEN);
    if (xe > xy) line(xy, y, fminf(xe, xr), y, hw, true, YELLOW);
    if (xe > xr) line(xr, y, xe, y, hw, true, RED);
  }
  if (pkS > MIN_DB) { float xp = x0 + span * dbT(pkS); line(xp, y - hw - 5, xp, y + hw + 5, 1.5f, true, pkS > Z_RED ? RED : WHITE); }
}
// A thin round-capped arc over the dial's 240 degrees with a fill to t (0..1).
void scaleArc(float t, uint16_t track, uint16_t col) {
  roundArc(194, 206, ARC_FROM, ARC_TO, track);
  if (t > 0.003f) roundArc(194, 206, ARC_FROM, ARC_FROM + clamp01(t) * (ARC_TO - ARC_FROM), col);
}
void fmtLufs(float v, char *t, int size, bool tenths = true) {   // "−18.4" with a true minus sign; "−∞" below −70 or unknown
  if (isnan(v) || v < -70) { snprintf(t, size, "\xE2\x88\x92\xE2\x88\x9E"); return; }
  int d = (int)lroundf(v * (tenths ? 10 : 1));
  const char *m = d < 0 ? "\xE2\x88\x92" : "";
  d = abs(d);
  if (tenths) snprintf(t, size, "%s%d.%d", m, d / 10, d % 10); else snprintf(t, size, "%s%d", m, d);
}
void fmtDuration(long s, char *t, int size) {
  if (s < 0) { snprintf(t, size, "\xE2\x80\x93:\xE2\x80\x93\xE2\x80\x93"); return; }
  if (s >= 3600) snprintf(t, size, "%ld:%02ld:%02ld", s / 3600, s / 60 % 60, s % 60);
  else snprintf(t, size, "%ld:%02ld", s / 60, s % 60);
}
// Civil date from days since 1970-01-01 (Howard Hinnant's algorithm).
void civil(long long z, int &y, int &m, int &d) {
  z += 719468;
  long long era = (z >= 0 ? z : z - 146096) / 146097;
  unsigned doe = (unsigned)(z - era * 146097);
  unsigned yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  unsigned doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  unsigned mp = (5 * doy + 2) / 153;
  d = doy - (153 * mp + 2) / 5 + 1;
  m = mp < 10 ? mp + 3 : mp - 9;
  y = (int)(yoe + era * 400) + (m <= 2);
}
// Local time from the PC's clock: "15:52", "Thu 19 Nov", the second. False until the PC has sent a T line.
bool clockNow(uint32_t now, char *hm, int hmSize, char *date, int dateSize, int &sec) {
  if (!clockValid) return false;
  long long u = clockUnix + (long long)((now - clockAt) / 1000) + clockOffMin * 60;
  long long days = u >= 0 ? u / 86400 : (u - 86399) / 86400;
  long s = (long)(u - days * 86400);
  sec = s % 60;
  snprintf(hm, hmSize, "%02ld:%02ld", s / 3600, s / 60 % 60);
  int y, m, dd;
  civil(days, y, m, dd);
  static const char *const WD[7] = {"Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"};
  static const char *const MO[12] = {"Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"};
  snprintf(date, dateSize, "%s %d %s", WD[(int)(((days % 7) + 11) % 7)], dd, MO[m - 1]);
  return true;
}

